-- 0006 — Vista Social: semáforo, muro de victorias, pócimas y joyas.
-- CORRER EN SUPABASE > SQL Editor > Run ANTES de hacer Redeploy en
-- Vercel: sin estas tablas, la vista Social muestra el aviso de
-- migración pendiente y no guarda estados, victorias, pócimas ni joyas.
-- Seguro de volver a correr: `if not exists` / DO con
-- `duplicate_object` no rompen nada si ya existe.
--
-- Semáforo: collaborators.social_state (escudo, cooperativo, fuegos,
-- taberna) — cada persona cambia su propio estado desde Social.
-- Muro de Victorias: social_posts + social_reactions (loot: pocion,
-- moneda, corona, cafe; una de cada ítem por persona y publicación).
-- Pócimas: social_kudos (3 por persona y día, nunca a uno mismo; lo
-- recibido se muestra en la repisa de cada persona).
-- Joyas Ocultas: social_joyas (1 por persona y semana, lunes a domingo).

alter table collaborators
  add column if not exists social_state text not null default 'cooperativo'
  check (social_state in ('escudo', 'cooperativo', 'fuegos', 'taberna'));

-- Victorias del día (máx 200 caracteres, lo valida la app).
create table if not exists social_posts (
  id bigint generated by default as identity primary key,
  collaborator_id bigint not null references collaborators(id) on delete cascade,
  body text not null,
  created_at timestamptz not null default now()
);

-- Reacciones tipo Loot a una victoria (toggle: se pone o se quita).
create table if not exists social_reactions (
  id bigint generated by default as identity primary key,
  post_id bigint not null references social_posts(id) on delete cascade,
  collaborator_id bigint not null references collaborators(id) on delete cascade,
  item text not null check (item in ('pocion', 'moneda', 'corona', 'cafe')),
  created_at timestamptz not null default now(),
  unique (post_id, collaborator_id, item)
);

-- Pócimas regaladas (3 monedas al día por persona; el servidor valida
-- el límite y que no sea a uno mismo).
create table if not exists social_kudos (
  id bigint generated by default as identity primary key,
  from_id bigint not null references collaborators(id) on delete cascade,
  to_id bigint not null references collaborators(id) on delete cascade,
  item text not null check (item in ('espresso', 'escudo', 'pocion', 'cafe')),
  message text,
  created_at timestamptz not null default now()
);

-- Joyas Ocultas (1 por persona y semana; el servidor valida la semana).
create table if not exists social_joyas (
  id bigint generated by default as identity primary key,
  collaborator_id bigint not null references collaborators(id) on delete cascade,
  kind text not null check (kind in ('cancion', 'comida', 'atajo', 'meme', 'otro')),
  body text not null,
  created_at timestamptz not null default now()
);

alter table social_posts enable row level security;
alter table social_reactions enable row level security;
alter table social_kudos enable row level security;
alter table social_joyas enable row level security;
do $$ begin
  create policy "public read" on social_posts for select using (true);
  create policy "public write" on social_posts for all using (true);
  create policy "public read" on social_reactions for select using (true);
  create policy "public write" on social_reactions for all using (true);
  create policy "public read" on social_kudos for select using (true);
  create policy "public write" on social_kudos for all using (true);
  create policy "public read" on social_joyas for select using (true);
  create policy "public write" on social_joyas for all using (true);
exception when duplicate_object then null; end $$;

do $$ begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'social_posts'
  ) then
    alter publication supabase_realtime add table social_posts;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'social_reactions'
  ) then
    alter publication supabase_realtime add table social_reactions;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'social_kudos'
  ) then
    alter publication supabase_realtime add table social_kudos;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'social_joyas'
  ) then
    alter publication supabase_realtime add table social_joyas;
  end if;
end $$;
