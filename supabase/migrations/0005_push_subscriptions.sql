-- 0005 — Notificaciones push (Chrome/escritorio) para comunicados de
-- Merlín y Corvo.
-- CORRER EN SUPABASE > SQL Editor > Run ANTES de hacer Redeploy en
-- Vercel: sin esta tabla, el botón "Activar notificaciones" de La
-- Carrera no guarda la suscripción (error falta_migracion_0005) y el
-- Master no puede enviar avisos. Seguro de volver a correr: `if not
-- exists` / DO con `duplicate_object` no rompen nada si ya existe.
--
-- Cómo funciona: cada participante que pulsa "Activar notificaciones"
-- en La Carrera guarda aquí su suscripción del navegador (endpoint +
-- llaves p256dh/auth). Cuando Osbed publica o prende un comunicado de
-- Merlín o Corvo, el servidor les manda la notificación con web-push
-- (llaves VAPID en Vercel). Solo comunicados: sumar/restar puntos no
-- manda avisos. Las suscripciones que el navegador rechaza (410/404)
-- se borran solas al enviar.

create table if not exists push_subscriptions (
  id bigint generated by default as identity primary key,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now()
);

alter table push_subscriptions enable row level security;
do $$ begin
  create policy "public read" on push_subscriptions for select using (true);
  create policy "public write" on push_subscriptions for all using (true);
exception when duplicate_object then null; end $$;
