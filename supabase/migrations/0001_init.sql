-- Juego RPG de Metas — migración 0001
-- Next.js 14 + Supabase (Postgres + Realtime)
-- UN SOLO numero de puntos por persona (saldo total) + sub-saldo de
-- puntualidad (punctuality_points): parte del total ganada solo con
-- acciones de puntualidad. Nunca pasa del total ni baja de 0.
-- Proyecto: https://ewwrbsoltopjswobwbgq.supabase.co

create extension if not exists "pgcrypto";

-- Colaboradores (solo puntos actuales)
create table if not exists collaborators (
  id bigint generated by default as identity primary key,
  name text not null,
  sprite int not null default 0 check (sprite >= 0 and sprite <= 11),
  points int not null default 0 check (points >= 0),
  punctuality_points int not null default 0 check (punctuality_points >= 0),
  area text,
  created_at timestamptz not null default now()
);

-- Catálogo de acciones (12) — se siembra desde la app si está vacío
-- linked_prize_id (migración 0004): premio ligado opcional; los puntos
-- de esa acción suman también a la bolsa exclusiva de ese premio.
create table if not exists action_types (
  id bigint primary key,
  label text not null,
  points int not null,
  linked_prize_id bigint -- FK a prizes, se agrega abajo (prizes aún no existe aquí)
);

-- Bolsas exclusivas por colaborador y premio (migración 0004). La del
-- BONO DE PUNTUALIDAD vive en collaborators.punctuality_points.
create table if not exists collaborator_bags (
  collaborator_id bigint not null references collaborators(id) on delete cascade,
  prize_id bigint not null, -- FK a prizes, se agrega abajo (prizes aún no existe aquí)
  points int not null default 0 check (points >= 0),
  primary key (collaborator_id, prize_id)
);

create table if not exists penalty_types (
  id bigint primary key,
  label text not null,
  points int not null
);

-- Historial de movimientos. reversed=true marca DESHECHO, no se borra.
create table if not exists point_events (
  id bigint generated by default as identity primary key,
  collaborator_id bigint not null references collaborators(id) on delete cascade,
  kind text not null check (kind in ('award','penalty','redeem','reversal','custom')),
  label text not null,
  points int not null,
  reason text,
  reversed boolean not null default false,
  bonus_from text,
  created_at timestamptz not null default now()
);
create index if not exists idx_point_events_collab on point_events(collaborator_id, created_at desc);

-- Premios con stock
create table if not exists prizes (
  id bigint generated by default as identity primary key,
  name text not null,
  cost int not null check (cost > 0),
  stock int not null default 0 check (stock >= 0)
);

-- FKs a prizes (no se podían poner inline arriba porque prizes se crea aquí).
do $$ begin
  alter table action_types add constraint action_types_linked_prize_fk foreign key (linked_prize_id) references prizes(id) on delete set null;
exception when duplicate_object then null; end $$;
do $$ begin
  alter table collaborator_bags add constraint collaborator_bags_prize_fk foreign key (prize_id) references prizes(id) on delete cascade;
exception when duplicate_object then null; end $$;

-- Canjes. Solo el Master aprueba / hace canje directo.
-- cost = costo TOTAL (cantidad x costo unitario); quantity = unidades.
create table if not exists redemptions (
  id bigint generated by default as identity primary key,
  collaborator_id bigint not null references collaborators(id) on delete cascade,
  prize_id bigint not null references prizes(id),
  prize_name text not null,
  cost int not null,
  quantity int not null default 1 check (quantity >= 1),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

-- Comunicados de Merlín
create table if not exists announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  active boolean not null default true,
  bonus_multiplier int check (bonus_multiplier in (2,3)),
  bonus_action_id bigint references action_types(id),
  created_at timestamptz not null default now()
);

-- Comunicados del Cuervo de RRHH (Corvo) — tabla aparte, recuadro aparte
create table if not exists crow_announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  active boolean not null default false,
  bonus_multiplier int check (bonus_multiplier in (2,3)),
  bonus_action_id bigint references action_types(id),
  created_at timestamptz not null default now()
);

-- Suscripciones push (notificaciones de escritorio): cada participante
-- que activa las notificaciones en La Carrera guarda aquí su
-- suscripción del navegador. Solo comunicados de Merlín y Corvo.
create table if not exists push_subscriptions (
  id bigint generated by default as identity primary key,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now()
);

-- Configuración: empresa, tema, temporada
create table if not exists settings (
  id bigint primary key,
  company_name text not null default 'SCRIPT TECNOLOGIAS DE LA INFORMACION',
  logo_url text,
  theme text not null default 'bosque' check (theme in ('clasico','bosque','oceano','atardecer','neon')),
  season text not null default 'navidad' check (season in ('navidad','halloween','primavera','verano','sin-temporada'))
);

